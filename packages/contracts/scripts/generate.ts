import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

import { parse } from "yaml";
import { z } from "zod";

const AttributeSchema = z
  .object({
    name: z.string().min(1),
    type: z.string().min(1),
    req: z.string().min(1),
  })
  .loose();

const SpanDefinitionSchema = z
  .object({
    attributes: z.array(AttributeSchema),
  })
  .loose();

const ContractSchema = z
  .object({
    schema_version: z.string().regex(/^\d+\.\d+$/),
    namespace_prefix: z.string().min(1),
    enums: z.record(z.string(), z.array(z.string().min(1))),
    resource_attributes: z.array(AttributeSchema),
    common_attributes: z.array(AttributeSchema),
    span_types: z.record(z.string(), SpanDefinitionSchema),
  })
  .loose();

const TaskTypeRegistrySchema = z.object({
  task_types: z.array(z.string().regex(/^[a-z][a-z0-9_]{1,31}$/)).min(1),
});

type Attribute = z.infer<typeof AttributeSchema>;
type Contract = z.infer<typeof ContractSchema>;

const schemaPath = fileURLToPath(
  new URL("../schema/agent-ops.schema.yaml", import.meta.url),
);
const taskTypePath = fileURLToPath(
  new URL("../registry/task_types.yaml", import.meta.url),
);
const tsOutputPath = fileURLToPath(new URL("../src/generated.ts", import.meta.url));
const sdkTsOutputPath = fileURLToPath(
  new URL("../../sdk-typescript/src/generated.ts", import.meta.url),
);
const jsonOutputPath = fileURLToPath(
  new URL("../generated/contract.json", import.meta.url),
);
const pythonOutputPath = fileURLToPath(
  new URL("../../sdk-python/src/agent_ops/generated.py", import.meta.url),
);

const contract = ContractSchema.parse(
  parse(await readFile(schemaPath, "utf8")),
);
const taskTypes = TaskTypeRegistrySchema.parse(
  parse(await readFile(taskTypePath, "utf8")),
).task_types;

const attributeNames = collectAttributeNames(contract);
assertNoDuplicate(attributeNames);
assertNoDuplicate(taskTypes);

const generatedTs = renderTypeScript(contract, taskTypes, attributeNames);
const generatedPython = renderPython(contract, taskTypes, attributeNames);
const generatedJson = `${JSON.stringify(
  {
    ...contract,
    task_types: taskTypes,
  },
  null,
  2,
)}\n`;

await Promise.all([
  writeOutput(tsOutputPath, generatedTs),
  writeOutput(sdkTsOutputPath, generatedTs),
  writeOutput(pythonOutputPath, generatedPython),
  writeOutput(jsonOutputPath, generatedJson),
]);

process.stdout.write(
  `Generated contract v${contract.schema_version}: ` +
    `${Object.keys(contract.enums).length} enums, ` +
    `${attributeNames.length} attributes, ${taskTypes.length} task types\n`,
);

function collectAttributeNames(input: Contract): string[] {
  const attributes: Attribute[] = [
    ...input.resource_attributes,
    ...input.common_attributes,
    ...Object.values(input.span_types).flatMap((span) => span.attributes),
  ];

  return [...new Set(attributes.map((attribute) => attribute.name))].sort();
}

function assertNoDuplicate(values: string[]): void {
  const seen = new Set<string>();
  for (const value of values) {
    if (seen.has(value)) {
      throw new Error(`Duplicate contract value: ${value}`);
    }
    seen.add(value);
  }
}

function renderTypeScript(
  input: Contract,
  supportedTaskTypes: string[],
  names: string[],
): string {
  const enumEntries = Object.entries(input.enums)
    .map(
      ([name, values]) =>
        `  ${toTsProperty(name)}: ${literalTuple(values)} as const,`,
    )
    .join("\n");

  const enumTypes = Object.entries(input.enums)
    .map(
      ([name]) =>
        `export type ${pascalCase(name)} = (typeof ENUMS.${toTsProperty(name)})[number];`,
    )
    .join("\n");

  const attributeEntries = names
    .map((name) => `  ${toTsProperty(name)}: ${JSON.stringify(name)},`)
    .join("\n");

  return `// Generated by scripts/generate.ts. Do not edit by hand.
export const SCHEMA_VERSION = ${JSON.stringify(input.schema_version)} as const;
export const NAMESPACE_PREFIX = ${JSON.stringify(input.namespace_prefix)} as const;
export const SDK_NAME = "agent-ops-otel-sdk" as const;

export const TASK_TYPES = ${literalTuple(supportedTaskTypes)} as const;
export type TaskType = (typeof TASK_TYPES)[number];

export const ENUMS = {
${enumEntries}
} as const;

${enumTypes}

export const ATTR = {
${attributeEntries}
} as const;

export type AttributeName = (typeof ATTR)[keyof typeof ATTR];

const SPAN_TYPE_SET = new Set<string>(ENUMS.spanType);
const TASK_TYPE_SET = new Set<string>(TASK_TYPES);

export function normalizeSpanType(value: string): SpanType {
  return SPAN_TYPE_SET.has(value) ? (value as SpanType) : "custom";
}

export function normalizeTaskType(value: string): string {
  return TASK_TYPE_SET.has(value) ? value : "other";
}
`;
}

function renderPython(
  input: Contract,
  supportedTaskTypes: string[],
  names: string[],
): string {
  const enumClasses = Object.entries(input.enums)
    .map(([name, values]) => {
      const className = pascalCase(name);
      const members = values
        .map((value) => `    ${toPythonMember(value)} = ${JSON.stringify(value)}`)
        .join("\n");
      return `class ${className}(StrEnum):\n${members}`;
    })
    .join("\n\n\n");

  const attributeMembers = names
    .map(
      (name) =>
        `    ${toPythonMember(name.toUpperCase())} = ${JSON.stringify(name)}`,
    )
    .join("\n");

  const taskMembers = supportedTaskTypes
    .map(
      (value) =>
        `    ${toPythonMember(value.toUpperCase())} = ${JSON.stringify(value)}`,
    )
    .join("\n");

  return `"""Generated by packages/contracts/scripts/generate.ts. Do not edit."""

from enum import StrEnum

SCHEMA_VERSION = ${JSON.stringify(input.schema_version)}
NAMESPACE_PREFIX = ${JSON.stringify(input.namespace_prefix)}
SDK_NAME = "agent-ops-otel-sdk"


${enumClasses}


class TaskType(StrEnum):
${taskMembers}


class Attr:
${attributeMembers}
`;
}

function literalTuple(values: string[]): string {
  return `[${values.map((value) => JSON.stringify(value)).join(", ")}]`;
}

function toTsProperty(value: string): string {
  const camel = value
    .split(/[._-]/)
    .filter(Boolean)
    .map((part, index) =>
      index === 0 ? part : `${part[0]?.toUpperCase() ?? ""}${part.slice(1)}`,
    )
    .join("");
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(camel)
    ? camel
    : JSON.stringify(camel);
}

function toPythonMember(value: string): string {
  const member = value
    .replace(/[^A-Za-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .toUpperCase();
  if (/^\d/.test(member)) {
    return `_${member}`;
  }
  return member || "_";
}

function pascalCase(value: string): string {
  const result = value
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => `${part[0]?.toUpperCase() ?? ""}${part.slice(1)}`)
    .join("");
  return result || "Generated";
}

async function writeOutput(path: string, content: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content, "utf8");
}

